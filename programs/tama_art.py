    fy, rows = body32(body, fy, art)
    rows = [list(r) for r in rows]
    f = scale2x(grid(dict(FACES)[face], 8, 5, face))
    for i, fr in enumerate(f):
        for j, c in enumerate(fr):
            if c == "#":
                x = rows[fy + i][8 + j]
                rows[fy + i][8 + j] = "." if x == "#" else "#"
    return ["".join(r).replace("#", "\u2588").replace(".", " ") for r in rows]


