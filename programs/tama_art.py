def grid(text, w, h, name):
    rows = [r for r in text.strip().splitlines()]
    assert len(rows) == h, f"{name}: {len(rows)} filas, no {h}"
    for r in rows:
        assert len(r) == w and set(r) <= {"#", "."}, f"{name}: fila mala {r!r}"
    return rows


def scale2x(rows):
    """Amplia al doble con Scale2x (EPX): cada pixel P pasa a 2x2; una
    esquina toma el color de sus dos vecinos si coinciden (y no forman una
    linea recta con los otros dos). Fuera de la rejilla, apagado."""
    h, w = len(rows), len(rows[0])
    px = lambda y, x: rows[y][x] == "#" if 0 <= y < h and 0 <= x < w else False
    out = [[False] * (2 * w) for _ in range(2 * h)]
    for y in range(h):
        for x in range(w):
            P = px(y, x)
            A, B, C, D = px(y - 1, x), px(y, x + 1), px(y, x - 1), px(y + 1, x)
            e0 = A if (C == A and C != D and A != B) else P
            e1 = B if (A == B and A != C and B != D) else P
            e2 = C if (D == C and D != B and C != A) else P
            e3 = D if (B == D and B != A and D != C) else P
            out[2 * y][2 * x], out[2 * y][2 * x + 1] = e0, e1
            out[2 * y + 1][2 * x], out[2 * y + 1][2 * x + 1] = e2, e3
    return ["".join("#" if v else "." for v in r) for r in out]


def body32(name, fy, art):
    """(fila de la cara en 32x32, filas 32x32) de un cuerpo dibujado a 32x32
    (tal cual) o a 16x16 (ampliado con Scale2x)."""
    n = len(art.strip().splitlines())
    if n == 32:
        return fy, grid(art, 32, 32, name)
    return 2 * fy, scale2x(grid(art, 16, 16, name))


def row_bytes(row):
    out = []
    for i in range(0, len(row), 8):
        v = 0
        for c in row[i:i + 8]:
            v = (v << 1) | (c == "#")
        out.append(v)
    return out


def emit(lines, label, rows, comment=True):
    data = []
    for r in rows:
        data += row_bytes(r)
    if comment:
        for r in rows:
            lines.append(f";   {r}")
    lines.append(f"{label}:")
    for i in range(0, len(data), 16):
        lines.append("    .db " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]))


