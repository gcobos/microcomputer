; ============================================================================
;  imagen.asm  -  Demo: imagen estatica (images/paisaje2.h) + musica de fondo
;  ("Eruption", Eddie Van Halen, instrumental de guitarra de 1978), en bucle
;  mientras se ve la imagen.
;
;  La imagen se dibuja UNA sola vez al arrancar (no hay animacion): un
;  paisaje de 128x64 a 1 bit, convertido directamente del fichero GIMP
;  `images/paisaje2.h` (formato INDEXED de 2 colores) al formato de
;  framebuffer real de compi (16 bytes/fila, bit7 = pixel mas a la
;  izquierda, 1 = encendido) -- ver la tabla `img_data` mas abajo.
;
;  La melodia (tabla `melody`) es una transcripcion de la notacion RTTTL que
;  se me paso, a pares (nota MIDI, duracion en pasos de 8 ms), reproducida
;  con el temporizador 3 -- mismo formato de tabla que programs/musica.asm,
;  salvo que aqui NO se deja un hueco de silencio entre notas (esa pieza es
;  un tapping muy rapido y ligado: el corte de ~24 ms entre notas que usa
;  musica.asm para distinguir repeticiones sonaria a tartamudeo en vez del
;  "legato" que la hace reconocible) y se usan pasos de 8 ms en vez de los
;  "ticks" de ~24 ms de musica.asm, para que las fusas/corcheas rapidas del
;  original no acumulen un desfase de tempo perceptible.
;
;  OJO -- la cadena RTTTL original tiene mas de 400 notas en una sola linea;
;  se ha transcrito con cuidado pero, dada su longitud, no se descarta algun
;  error puntual de nota/duracion suelto. Si algo no encaja al oido, decidmelo
;  y lo repaso contra el original.
;
;  Controles:
;     encoder DIRECCION pulsa -> termina (apaga el sonido y vuelve al slot 0)
;
;  Ensamblar y enviar al slot 18:
;     python3 tools/casm.py programs/imagen.asm -o programs/imagen.bin
;     python3 tools/compi_send.py --port /dev/ttyACM0 --slot 18 programs/imagen.bin
;
;  Probar sin el aparato:
;     python3 tools/sim.py programs/imagen.bin --steps 2000000
;
;  La ISA y los puertos: ../docs/isa.md
; ============================================================================

    .slot 18

    .name "IMAGE"

    .category DEMO
    .org 0x0000

; --- puertos (ver ../docs/isa.md) -------------------------------------------
P_DIR_BTN   = 0x0601
P_T3        = 0x0623      ; temporizador 3 (8 ms/paso)
P_SND_N     = 0x0632      ; nota MIDI a sonar (0 = silencio)
P_PROG_LOAD = 0x0640       ; cargar slot (OUT n. de slot): salto a otro programa

; ============================================================================
;  ARRANQUE
; ============================================================================
start:
    CALL draw_image
    MOV AL,#0
    STA [g_exit],AL

; ============================================================================
;  BUCLE PRINCIPAL: reproduce la melodia en bucle hasta DIRECCION
; ============================================================================
pm_rs:
    MOV DX,#melody
pm_nx:
    CALL poll_exit
    LDA AL,[g_exit]
    CMP AL,#0
    JMPNZ pm_x

    LDA AL,[DX]                ; nota MIDI (0 = silencio)
    CMP AL,#0xFF
    JMPZ pm_rs                  ; fin de la tabla -> repite desde el principio
    STA [cur_note],AL
    INC DX

    LDA AL,[DX]                ; duracion, en pasos de 8 ms
    STA [cur_dur],AL
    INC DX

    LDA AL,[cur_note]
    OUT (P_SND_N),AL
    LDA AL,[cur_dur]
    CALL frame_wait
    JMP pm_nx

pm_x:
    MOV AL,#0
    OUT (P_SND_N),AL
    CALL wait_dir_release
    MOV AL,#0
    OUT (P_PROG_LOAD),AL        ; vuelve al sistema (sisop, slot 0)
    HALT                         ; solo si el slot 0 estuviera vacio

; --- draw_image: vuelca los 1024 bytes de `img_data` al framebuffer real, de
; un tiron (sin comparar con lo que hubiera antes -- a diferencia del
; shadow/blit de cubo.asm/calc.asm/esquiva.asm, aqui no hace falta: se
; dibuja una sola vez, no cada fotograma). BX = puerto (0..1023), DX =
; puntero de RAM a img_data -- ambos de 16 bits, avanzan con INC (docs/isa.md
; SS4d); el final se detecta mirando BH tras cada vuelta: BX solo llega a
; valer exactamente 1024 (BH=4) la vez que cruza ese limite viniendo de
; abajo, mismo criterio que clr_shadow/blit en otros programas.
draw_image:
    MOV BX,#0
    MOV DX,#img_data
di_l:
    LDA AL,[DX]
    OUT (BX),AL
    INC BX
    INC DX
    MOV AL,BH
    CMP AL,#4
    JMPNZ di_l
    RET

; --- frame_wait: espera AL*8 ms con el temporizador 3 -----------------------
frame_wait:
    OUT (P_T3),AL
fw_l:
    IN  AL,(P_T3)
    CMP AL,#0
    JMPNZ fw_l
    RET

; --- poll_exit: marca g_exit si DIRECCION esta pulsado ----------------------
poll_exit:
    IN  AL,(P_DIR_BTN)
    CMP AL,#0
    JMPZ pe_d
    MOV AL,#1
    STA [g_exit],AL
pe_d:
    RET

; --- wait_dir_release: espera a que se suelte DIRECCION ---------------------
wait_dir_release:
    IN  AL,(P_DIR_BTN)
    CMP AL,#0
    JMPZ wdr_d
    MOV AL,#2
    CALL frame_wait
    JMP wait_dir_release
wdr_d:
    RET

; ============================================================================
;  DATOS
; ============================================================================
g_exit:     .space 1
cur_note:   .space 1
cur_dur:    .space 1

